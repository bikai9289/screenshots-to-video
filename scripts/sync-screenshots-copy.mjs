import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const copy = JSON.parse(fs.readFileSync('scripts/screenshots-copy.json','utf8'));
const keys = Object.keys(copy.en);
if (keys.some(key=>!copy.zh[key]) || Object.keys(copy.zh).length!==keys.length) throw new Error('Locale keys differ');
for (const locale of ['en','zh']) {
  const file = `messages/${locale}.json`;
  const messages = JSON.parse(fs.readFileSync(file,'utf8'));
  for (const key of keys) messages[`landing.screenshots.${key}`] = copy[locale][key];
  fs.writeFileSync(file,JSON.stringify(messages,null,2)+'\n');
}
fs.mkdirSync('src/blocks/screenshots-to-video',{recursive:true});
fs.writeFileSync('src/blocks/screenshots-to-video/content.ts',`// Generated by scripts/sync-screenshots-copy.mjs.\nimport { m } from '@/paraglide/messages.js';\n\nexport function getScreenshotsCopy() {\n  return {\n${keys.map(key=>`    ${key}: m['landing.screenshots.${key}'](),`).join('\n')}\n  };\n}\n`);
const require = createRequire(import.meta.url);
const postcssDir = fs.readdirSync('node_modules/.pnpm').find(name=>name.startsWith('postcss@'));
const postcss = require(path.resolve('node_modules/.pnpm',postcssDir,'node_modules/postcss'));
const css = postcss.parse(fs.readFileSync('designs/screenshots-to-video/styles.css','utf8'));
css.walkRules(rule=>{
  if(rule.parent.type==='atrule' && rule.parent.name.includes('keyframes')) return;
  rule.selectors=rule.selectors.map(selector=>{
    if(selector===':root' || selector==='body' || selector==='html') return '.stv-site';
    return `.stv-site ${selector}`;
  });
});
fs.writeFileSync('src/components/screenshots-to-video/screenshots.css', `/* Scoped from the user-approved first UI. */\n${css.toString()}\n`);
fs.mkdirSync('public/imgs/screenshots-to-video',{recursive:true});
fs.copyFileSync('designs/screenshots-to-video/assets/orbit-dashboard.png','public/imgs/screenshots-to-video/orbit-dashboard.png');
console.log(`Synced ${keys.length} messages per locale, content, scoped CSS and sample asset.`);
